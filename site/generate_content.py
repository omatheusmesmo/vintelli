#!/usr/bin/env python3
"""Generate the spike list and the keymap page of the project site from docs/.

Writes content/decisions.md and content/keymap.md, both generated and gitignored.
Fails when a relative link in docs/keymap.md does not resolve in the repository.
"""

import re
import sys
from pathlib import Path

SITE_DIR = Path(__file__).resolve().parent
REPO_ROOT = SITE_DIR.parent
DOCS_DIR = REPO_ROOT / "docs"
SPIKES_DIR = DOCS_DIR / "spikes"
CONTENT_DIR = SITE_DIR / "content"
REPO_BLOB_URL = "https://github.com/omatheusmesmo/vintelli/blob/main/"
REPO_TREE_URL = "https://github.com/omatheusmesmo/vintelli/tree/main/"
SPIKE_SUFFIXES = (".md", ".json")
MARKDOWN_LINK = re.compile(r"\]\(([^)\s]+)\)")
GENERATED_NOTICE = "<!-- Generated by site/generate_content.py from the repository. Do not edit. -->"


class SiteGenerationError(Exception):
    pass


def spike_files():
    return sorted(
        path
        for path in SPIKES_DIR.rglob("*")
        if path.is_file() and path.suffix in SPIKE_SUFFIXES
    )


def spike_title(path):
    if path.suffix == ".md":
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return line[2:].strip().replace("`", "")
    return path.name


def repo_url(relative_path):
    target = REPO_ROOT / relative_path
    if target.is_dir():
        return REPO_TREE_URL + relative_path.as_posix()
    return REPO_BLOB_URL + relative_path.as_posix()


def render_decisions():
    lines = [
        "---",
        "title: Decisions and measurements",
        "description: Every spike in docs/spikes, listed from the repository at build time.",
        "layout: base",
        "---",
        "",
        GENERATED_NOTICE,
        "",
        "Each spike records a decision behind Vintelli or a measurement that backed one. "
        "The list is generated from the files in `docs/spikes/`, and every entry links to the file in the repository.",
        "",
    ]
    for path in spike_files():
        relative = path.relative_to(REPO_ROOT)
        lines.append(f"- [{spike_title(path)}]({repo_url(relative)}) (`{relative.as_posix()}`)")
    return "\n".join(lines) + "\n"


def rewrite_link(target):
    if target.startswith("#") or re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", target):
        return target
    path_part, _, fragment = target.partition("#")
    resolved = (DOCS_DIR / path_part).resolve()
    if not resolved.exists():
        raise SiteGenerationError(f"docs/keymap.md links to a missing path: {target}")
    relative = resolved.relative_to(REPO_ROOT)
    url = repo_url(relative)
    return f"{url}#{fragment}" if fragment else url


def render_keymap():
    source = (DOCS_DIR / "keymap.md").read_text(encoding="utf-8").splitlines()
    if source and source[0].startswith("# "):
        source = source[1:]
    body = MARKDOWN_LINK.sub(lambda match: f"]({rewrite_link(match.group(1))})", "\n".join(source).strip())
    header = [
        "---",
        "title: Keymap",
        "description: The named actions behind every key, the profiles and the chords a terminal cannot deliver.",
        "layout: base",
        "---",
        "",
        GENERATED_NOTICE,
        "",
        "Rendered from [`docs/keymap.md`](" + REPO_BLOB_URL + "docs/keymap.md). Every key goes through a named "
        "action, so a user keymap file can rebind an action without a code change.",
        "",
        "",
    ]
    return "\n".join(header) + body + "\n"


def main():
    try:
        CONTENT_DIR.mkdir(parents=True, exist_ok=True)
        (CONTENT_DIR / "decisions.md").write_text(render_decisions(), encoding="utf-8")
        (CONTENT_DIR / "keymap.md").write_text(render_keymap(), encoding="utf-8")
    except SiteGenerationError as error:
        print(f"generate_content: {error}", file=sys.stderr)
        return 1
    print(f"generate_content: {len(spike_files())} spikes, keymap rendered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
